# City detector (name plate + city art): random forest "city" vs everything else (villages, terrain, clouds …).
# Usage: python3 city.py dataset.json[,more.json] [out.js]   (extra files: e.g. cities / non-cities checked by hand)   → leave-one-screenshot-out report, then the model as JS
import sys, json, numpy as np
from collections import defaultdict
from PIL import Image
from sklearn.ensemble import ExtraTreesClassifier
sys.path.insert(0, __import__('os').path.dirname(__file__))
from feat import city_features
from export import export

def load(paths):
    d = [t for p in paths.split(',') for t in json.load(open(p))]; by = defaultdict(list)
    for t in d: by[t['img']].append(t)
    X, y, g = [], [], []
    global NB; NB = []
    for gi, (img, ts) in enumerate(by.items()):
        a = np.asarray(Image.open(img).convert('RGB'))
        for t in ts:
            pos = t['label'].startswith('city'); w = t['w']
            # positives: a few shifted copies (the grid is never perfect)
            shifts = [(0, 0), (0.06, 0), (-0.06, 0), (0, 0.05), (0, -0.05), (0.05, 0.04), (-0.05, -0.04)] if pos else [(0, 0)]
            for dx, dy in shifts:
                X.append(city_features(a, t['x'] + dx * w, t['y'] + dy * w, w)); y.append(1 if pos else 0); g.append(gi)
            # the 8 neighbours of a city are NOT the city – above all the tile above, into which a big city rises
            # (without these the tile above could win the neighbour check in the app)
            if pos:
                for nx, ny in ((0.5, 0.3), (-0.5, 0.3), (0.5, -0.3), (-0.5, -0.3), (1, 0), (-1, 0), (0, 0.6), (0, -0.6)):
                    xx, yy = t['x'] + nx * w, t['y'] + ny * w
                    if any(o['label'].startswith('city') and abs(o['x'] - xx) < 0.3 * w and abs(o['y'] - yy) < 0.2 * w for o in ts): continue
                    X.append(city_features(a, xx, yy, w)); y.append(0); g.append(gi); NB.append(len(y) - 1)
    return np.array(X), np.array(y), np.array(g)

# extra trees did best leave-one-screenshot-out (with the neighbour check in the app: 41/48 cities, 3 false alarms at 0.5)
def rf(): return ExtraTreesClassifier(n_estimators=100, max_depth=14, min_samples_leaf=2, class_weight='balanced', random_state=0)

if __name__ == '__main__':
    X, y, g = load(sys.argv[1])
    print(X.shape, y.sum(), 'positive samples')
    P = np.zeros(len(y))
    for gi in np.unique(g):
        tr, te = g != gi, g == gi
        if y[tr].sum() == 0: continue
        m = rf().fit(X[tr], y[tr]); P[te] = m.predict_proba(X[te])[:, 1]
    # only the unshifted samples count for the report: first sample of each positive group of 7
    keep = np.ones(len(y), bool); i = 0
    while i < len(y):
        if y[i] == 1: keep[i + 1:i + 7] = False; i += 7
        else: i += 1
    nb = np.zeros(len(y), bool); nb[NB] = True
    keep &= ~nb   # the report counts the labelled tiles only (neighbour negatives: see 'tile above wins' below)
    # how often a neighbour of a city scores higher than the city itself (→ the app would pick the wrong tile)
    first = [i for i in range(len(y)) if y[i] == 1 and keep[i]]
    lose = 0
    for i in first:
        nbs = [j for j in NB if g[j] == g[i] and j > i and j < i + 7 + 8 + 1]
        if any(P[j] > P[i] for j in nbs): lose += 1
    print(f'a neighbour scores higher than the city: {lose} of {len(first)} cities')
    for th in (0.3, 0.4, 0.5, 0.6, 0.7):
        yy, pp = y[keep], P[keep] >= th
        tp = (yy & pp).sum(); fn = (yy & ~pp).sum(); fp = (~yy.astype(bool) & pp).sum()
        print(f'th {th}: found {tp}/{tp+fn}  false alarms {fp} of {(~yy.astype(bool)).sum()} other tiles')
    if len(sys.argv) > 2:
        m = rf().fit(X, y)
        data = dict(export(m), version=3, nFeat=int(X.shape[1]))
        with open(sys.argv[2], 'w') as f:
            f.write('// Generated by tools/tilemodel/city.py – do not edit. City detector v3 (extra trees, name plate + tile features;\n'
                    '// %d city tiles and %d other tiles from %d screenshots).\nwindow.PP = window.PP || {};\nPP.CITY_MODEL = ' % (int(y[keep].sum()), int((1 - y[keep]).sum()), len(set(g.tolist())))
                    + json.dumps(data, separators=(',', ':')) + ';\n')
        print('model →', sys.argv[2], __import__('os').path.getsize(sys.argv[2]) // 1024, 'KB')

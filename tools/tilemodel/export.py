#!/usr/bin/env python3
# Trains the tile terrain model and writes js/tilemodel-data.js (PP.TILE_MODEL).
# Data (screenshots + labels) is NOT in the repo – see tools/tilemodel/README.md.
# usage: python3 tools/tilemodel/export.py <dataset.json> [out.js]
#   dataset.json: [{ "img": path, "grid": {"w","cx","cy"}, "tiles": [{"x","y","label"}] }, …]
import sys, json, os, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from feat import features
from PIL import Image
from sklearn.ensemble import RandomForestClassifier

TERR = {'field': 'field', 'forest': 'forest', 'mountain': 'mountain', 'water': 'water', 'city': 'city', 'village': 'city',
        'cloud': 'cloud', 'edge': 'outside', 'space': 'outside', 'farm': 'field'}
TREES, DEPTH, LEAF = 50, 10, 3

def load(ds):
    X, Y = [], []
    for it in ds:
        a = np.asarray(Image.open(it['img']).convert('RGB')).astype(np.float32); w = it['grid']['w']
        for t in it['tiles']:
            ter = TERR.get(t['label'].split('+')[0])
            if ter: X.append(features(a, t['x'], t['y'], w)); Y.append(ter)
    return np.array(X), np.array(Y)

def export(m, n_feat):
    trees = []
    for e in m.estimators_:
        t = e.tree_
        val = t.value[:, 0, :]; val = val / val.sum(1, keepdims=True)
        # node arrays: feature (-1 = leaf), threshold, left, right; leaves carry the class distribution
        trees.append({'f': [int(v) for v in t.feature], 't': [round(float(v), 5) for v in t.threshold],
                      'l': [int(v) for v in t.children_left], 'r': [int(v) for v in t.children_right],
                      'v': [[round(float(p), 3) for p in val[i]] if t.feature[i] < 0 else 0 for i in range(t.node_count)]})
    return {'classes': [str(c) for c in m.classes_], 'nFeat': n_feat, 'trees': trees}

if __name__ == '__main__':
    ds = json.load(open(sys.argv[1])); out = sys.argv[2] if len(sys.argv) > 2 else 'js/tilemodel-data.js'
    X, Y = load(ds)
    m = RandomForestClassifier(n_estimators=TREES, max_depth=DEPTH, min_samples_leaf=LEAF, class_weight='balanced', random_state=0).fit(X, Y)
    data = export(m, X.shape[1])
    with open(out, 'w') as f:
        f.write('// Generated by tools/tilemodel/export.py – do not edit. Tile terrain model (random forest, ' +
                f'{TREES} trees, {len(Y)} labelled tiles from {len(ds)} screenshots).\n')
        f.write('window.PP = window.PP || {};\nPP.TILE_MODEL = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('wrote', out, os.path.getsize(out) // 1024, 'KB;', {c: int((Y == c).sum()) for c in m.classes_})

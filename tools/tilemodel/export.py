#!/usr/bin/env python3
# Trains the tile models and writes js/tilemodel-data.js (PP.TILE_MODEL, v2):
#   terrain  field / forest / mountain / water / city (villages too) / cloud / outside
#   field    resource on a field: none / crop / fruit
#   mountain resource on a mountain: none / metal
# Data (screenshots + labels) is NOT in the repo – see README.md.
# usage: python3 tools/tilemodel/export.py <dataset.json> [out.js]
#   dataset.json: [{ "img": path, "w": tile width, "x": …, "y": …, "label": "field+crop+unit" }, …]
import sys, json, os, numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from feat import all_features
from PIL import Image
from sklearn.ensemble import RandomForestClassifier

TERR = {'field': 'field', 'forest': 'forest', 'mountain': 'mountain', 'water': 'water', 'city': 'city', 'village': 'city',
        'cloud': 'cloud', 'edge': 'outside', 'space': 'outside', 'outside': 'outside', 'farm': 'field'}

def load(items):
    cache, X, T, RES = {}, [], [], []
    for it in items:
        parts = it['label'].split('+'); ter = TERR.get(parts[0])
        if not ter: continue
        if it['img'] not in cache: cache[it['img']] = np.asarray(Image.open(it['img']).convert('RGB')).astype(np.float32)
        X.append(all_features(cache[it['img']], it['x'], it['y'], it['w'])); T.append(ter)
        RES.append('crop' if 'crop' in parts else 'fruit' if 'fruit' in parts else 'metal' if 'metal' in parts or 'ore' in parts else 'none')
    return np.array(X), np.array(T), np.array(RES)

def export(m):
    # compact: f = feature per node (-1 = leaf), t = threshold, r = right child (left child is always the next node),
    # v = class probabilities of the leaves in node order, in whole percent
    trees = []
    for e in m.estimators_:
        t = e.tree_; val = t.value[:, 0, :]; val = val / val.sum(1, keepdims=True)
        assert all(t.children_left[i] == i + 1 for i in range(t.node_count) if t.feature[i] >= 0)
        leaf = [i for i in range(t.node_count) if t.feature[i] < 0]
        trees.append({'f': [int(v) if v >= 0 else -1 for v in t.feature],
                      't': [float('%.4g' % v) if t.feature[i] >= 0 else 0 for i, v in enumerate(t.threshold)],
                      'r': [int(v) if t.feature[i] >= 0 else 0 for i, v in enumerate(t.children_right)],
                      'v': [int(round(p * 100)) for i in leaf for p in val[i]]})
    return {'classes': [str(c) for c in m.classes_], 'trees': trees}

def rf(n, depth): return RandomForestClassifier(n_estimators=n, max_depth=depth, min_samples_leaf=2, class_weight='balanced', random_state=0)

if __name__ == '__main__':
    items = json.load(open(sys.argv[1])); out = sys.argv[2] if len(sys.argv) > 2 else 'js/tilemodel-data.js'
    X, T, RES = load(items)
    terrain = rf(100, 14).fit(X, T)
    fm = (T == 'field') & np.isin(RES, ['none', 'crop', 'fruit']); field = rf(60, 12).fit(X[fm], RES[fm])
    mm = (T == 'mountain') & np.isin(RES, ['none', 'metal']); mount = rf(40, 10).fit(X[mm], RES[mm])
    data = {'version': 2, 'nFeat': int(X.shape[1]), 'terrain': export(terrain), 'field': export(field), 'mountain': export(mount)}
    with open(out, 'w') as f:
        f.write('// Generated by tools/tilemodel/export.py – do not edit. Tile models v2 (random forests; ' +
                f'{len(T)} labelled tiles from {len(set(i["img"] for i in items))} screenshots).\n')
        f.write('window.PP = window.PP || {};\nPP.TILE_MODEL = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    import collections
    print('wrote', out, os.path.getsize(out) // 1024, 'KB;', dict(collections.Counter(T)), 'field res', dict(collections.Counter(RES[fm])), 'mountain res', dict(collections.Counter(RES[mm])))
